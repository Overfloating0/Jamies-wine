// Build the standalone REFramework script without third-party Node dependencies.
const fs = require('node:fs'), path = require('node:path');
const root = path.resolve(__dirname, '..');
const modules = ['effects','clock','config','hotkeys','targets','sf6_adapter','throw_history','throw_rules','stomp_detector','throw_shrink','throw_probe','background_models','background','main'];
const main = fs.readFileSync(path.join(root,'src/jellymod/main.lua'),'utf8');
const version = main.match(/local VERSION = "([0-9.]+)"/)[1];
const included = new Set();
let bundle = `-- Jamie's Wine ${version}\n-- SPDX-License-Identifier: AGPL-3.0-only\n-- Generated by scripts/build.cjs; corresponding source is included in src/.\nlocal __jamieswine_modules = {}\n`;
for (const name of modules) {
    const source = fs.readFileSync(path.join(root,`src/jellymod/${name}.lua`),'utf8').replace(/\r\n/g,'\n')
        .replace(/require\("jellymod\.([a-z0-9_]+)"\)/g,(_,dependency)=>{
            if (!included.has(dependency)) throw Error(`Missing dependency: ${dependency}`);
            return `__jamieswine_modules["${dependency}"]`;
        });
    if (/\brequire\s*\(/.test(source)) throw Error('Unbundled dependency: '+name);
    bundle += `\n__jamieswine_modules["${name}"] = (function()\n${source}\nend)()\n`;
    included.add(name);
}
const target = path.join(root,'reframework/autorun/jamieswine.lua');
fs.mkdirSync(path.dirname(target),{recursive:true});
fs.writeFileSync(target,bundle);
console.log(`Built Jamie's Wine ${version}: ${target}`);
